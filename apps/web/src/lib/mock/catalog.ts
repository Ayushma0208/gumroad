export function getFeaturedProducts(): Product[] {
  return products.filter((product) => product.featured);
}

export function getTrendingProducts(): Product[] {
  return products.filter((product) => product.trending);
}

export function getEditorsPicks(): Product[] {
  return products.filter((product) => product.editorsPick);
}

export function getProductBySlug(slug: string): Product | undefined {
  return products.find((product) => product.slug === slug);
}

export function getFeaturedProductForCreator(slug: string): Product | undefined {
  return products.find((product) => product.creator.slug === slug && product.featured);
}
